def image_sampler(theta, pi, num_images):
    """ Inputs: parameters theta and pi, and number of images to sample
    Returns the sampled images (N_images x N_features)"""

    # YOU NEED TO WRITE THIS PART
    # sample a class for each image
    classes = np.random.choice(len(pi), size=num_images, p=pi)

    # create space for generated images
    images = np.zeros((num_images, theta.shape[0]))

    # generate pixels conditional on the sampled class
    for i, c in enumerate(classes):
        images[i] = np.random.binomial(1, theta[:, c])

    return images


