def train_map_estimator(train_images, train_labels):
    """ Inputs: train_images (N_samples x N_features), train_labels (N_samples x N_classes)
        Returns the MAP estimator theta_est (N_features x N_classes) and the MLE
        estimator pi_est (N_classes)"""

    # YOU NEED TO WRITE THIS PART:
    # MAP estimate using Beta(4, 3) prior
    N_k = np.sum(train_labels, axis=0) # Number of examples belonging to each class: (N_classes,)
    S = train_images.T @ train_labels # Number of 1s for each feature/class pair
    theta_est = (S + 3) / (N_k[None, :] + 5) # MAP of theta

    # MLE estimate of class probabilities
    pi_est = N_k / train_labels.shape[0]

    return theta_est, pi_est

